type TranslationKey = keyof typeof translations.en

type I18nCtx = {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: TranslationKey) => string
}

const I18nContext = createContext<I18nCtx>({
  locale: 'en',
  setLocale: () => {},
  t: (key: TranslationKey) => translations.en[key] || key,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en')
  const [mounted, setMounted] = useState(false)

  useEffect(() => {
    const saved = localStorage.getItem('kairos-locale') as Locale | null
    if (saved === 'en' || saved === 'de') setLocaleState(saved)
    setMounted(true)
  }, [])

  function setLocale(l: Locale) {
    setLocaleState(l)
    localStorage.setItem('kairos-locale', l)
  }

  function t(key: TranslationKey): string {
    return translations[locale][key] || translations.en[key] || key
  }

  if (!mounted) return (
    <I18nContext.Provider value={{ locale: 'en', setLocale: () => {}, t: (key: TranslationKey) => translations.en[key] || key }}>
      {children}
    </I18nContext.Provider>
  )

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
